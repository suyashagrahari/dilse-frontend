// The em/en dashes and the curly apostrophes share plots with their ASCII kin so
// that copy pasted from a design doc still renders.
DOT_FONT["—"] = DOT_FONT["-"];
DOT_FONT["–"] = DOT_FONT["-"];
DOT_FONT["’"] = DOT_FONT["'"];
DOT_FONT["‘"] = DOT_FONT["'"];
DOT_FONT["“"] = DOT_FONT['"'];
DOT_FONT["”"] = DOT_FONT['"'];

export const glyphFor = (ch: string): string[] => DOT_FONT[ch] ?? DOT_FONT[ch.toUpperCase()] ?? BLANK;

/** Only characters the plotter knows survive; everything else becomes a space. */
export const normaliseForDots = (s: string): string =>
  s
    .toUpperCase()
    .split("")
    .map((c) => (DOT_FONT[c] ? c : " "))
    .join("");
