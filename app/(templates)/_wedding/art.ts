export type WeddingArtId = keyof typeof WEDDING_ART;

/** src (1×), srcSet (1× + 2×) and the intrinsic size of one pack image. */
export function art(id: WeddingArtId) {
  const [w, h] = WEDDING_ART[id];
  const one = templateMedia("wedding", `v2/art/${id}.webp`);
  const two = templateMedia("wedding", `v2/art/${id}@2x.webp`);
  return { src: one, srcSet: `${one} 1x, ${two} 2x`, w, h };
}

/** The 2× URL alone (CSS backgrounds, plates). */
export const art2x = (id: WeddingArtId) => templateMedia("wedding", `v2/art/${id}@2x.webp`);
